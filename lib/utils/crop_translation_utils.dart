  static String translateVariety(String variety) {
    final lower = variety.trim().toLowerCase();
    return varietyTranslations[lower] ?? variety;
  }

  static String translate(String englishName) {
    String original = englishName.trim();
    String lower = original.toLowerCase();
    
    // 1. Exact match first
    if (cropTranslations.containsKey(lower)) {
      return cropTranslations[lower]!;
    }

    // 2. Sophisticated variety handling
    final keys = cropTranslations.keys.toList()
      ..sort((a, b) => b.length.compareTo(a.length));

    // Identify the Main Crop (the one that appears in the string and is NOT just a variety term)
    String? baseKey;
    for (var key in keys) {
      if (lower.contains(key) && !_varietyTerms.contains(key)) {
        baseKey = key;
        break;
      }
    }

    if (baseKey != null) {
      String baseTranslation = cropTranslations[baseKey]!;
      
      // Clean up the rest of the string to find varieties
      String rest = lower.replaceAll(baseKey, '').replaceAll('(', '').replaceAll(')', '').trim();
      if (rest.isNotEmpty) {
        List<String> translatedParts = [];
        Set<String> seenWords = {baseTranslation}; // Start by ignoring the base crop translation in suffix
        
        // Search through ALL keys in the rest of the string
        String remainingRest = rest;
        for (var key in keys) {
           if (key.length < 3) continue; // Skip very short generic keys
           
           if (remainingRest.contains(key)) {
             String partTranslation = cropTranslations[key]!;
             if (!seenWords.contains(partTranslation)) {
               translatedParts.add(partTranslation);
               seenWords.add(partTranslation);
             }
             // Mark this part as processed
             remainingRest = remainingRest.replaceAll(key, '').trim();
           }
        }
        
        // Failsafe: If there are still words in remainingRest that weren't matched,
        // add them as uppercase so we don't lose information (like 'Shankar' if it was missing)
        if (remainingRest.isNotEmpty) {
           List<String> unknownParts = remainingRest.split(RegExp(r'[\s\(\)]+'));
           for (var p in unknownParts) {
             if (p.length >= 2 && !seenWords.contains(p.toUpperCase())) {
                translatedParts.add(p.toUpperCase());
             }
           }
        }
        
        if (translatedParts.isNotEmpty) {
          return '$baseTranslation (${translatedParts.join(" ")})';
        }
      }
      return baseTranslation;
    }

    // Fallback to substring matching if no base crop identified (like 'Potato Punjab' where 'potato' is the base)
    for (var key in keys) {
      if (lower.contains(key)) {
        return cropTranslations[key]!;
      }
    }
    
    return original;
  }
